// Writes vienna-dev.html: the studio page (studio.html, unchanged) with the Vienna Piano Stage added, for local
// preview. Generated, so it cannot drift from the studio. The public build (virtualspace/build.mjs) makes its
// /piano-stage page with the same `stagePage` (marked noindex: the studio page stays the one search engines see).
//   node virtual-studio/vienna/dev-page.mjs && python3 -m http.server 8130   →   http://localhost:8130/vienna-dev.html
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
// the studio page's html → the same page with the stage
// `melbourne`: the Underground DJ Room under the studio as well (virtual-studio/melbourne), on its own dev page
export function stagePage(html, title = 'Vienna Piano Stage (dev) — DISTANCE // ZERO', { melbourne = false } = {}) {
  const swap = (from, to) => { if (!html.includes(from)) throw new Error('studio.html changed, not found: ' + from); html = html.replace(from, to); };
  swap('<title>Virtual Studio — DISTANCE // ZERO</title>', `<title>${title}</title>`);
  swap('<meta name="robots" content="index, follow, max-image-preview:large">', '<meta name="robots" content="noindex, nofollow">');
  swap('    const app = await start({\n      canvas, quality: tier(), progress,',
    melbourne
      ? "    const { vienna } = await import('./virtual-studio/vienna/index.js');\n    const { withVienna } = await import('./virtual-studio/melbourne/index.js');\n    const app = await start({\n      canvas, quality: tier(), progress, extend: withVienna(vienna),"
      : "    const { vienna } = await import('./virtual-studio/vienna/index.js');\n    const app = await start({\n      canvas, quality: tier(), progress, extend: vienna,");
  return html;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const html = stagePage(fs.readFileSync(path.join(ROOT, 'studio.html'), 'utf8'));
  fs.writeFileSync(path.join(ROOT, 'vienna-dev.html'), '<!-- GENERATED by virtual-studio/vienna/dev-page.mjs from studio.html: do not edit -->\n' + html);
  const both = stagePage(fs.readFileSync(path.join(ROOT, 'studio.html'), 'utf8'), 'Virtual Studio, two levels (dev) — DISTANCE // ZERO', { melbourne: true });
  fs.writeFileSync(path.join(ROOT, 'melbourne-dev.html'), '<!-- GENERATED by virtual-studio/vienna/dev-page.mjs from studio.html: do not edit -->\n' + both);
  console.log('wrote vienna-dev.html, melbourne-dev.html');
}
