// The Piano Stage's repertoire is DJ Andy'K's existing song library (the djandyk-landing project: src/data/*.ts, the
// song sheets in public/downloads/song-sheets, the Opus No. 1 Vienna scores). This script reads that library and
// writes a read-only index for the stage (repertoire.js): titles, the verified key, BPM and main chord progression,
// the original recording's address and the song sheet or score. Nothing is copied, transcribed or made up: a field
// the library does not have stays empty. Run again when the library changes.
//   node virtual-studio/vienna/repertoire-sync.mjs [--check] [path/to/djandyk-landing]
//   --check: asks djandykofficial.com whether each recording, sheet and score is there (HEAD requests only)
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const args = process.argv.slice(2), check = args.includes('--check');
const LIB = path.resolve(args.find(a => !a.startsWith('--')) || path.join(os.homedir(), 'djandyk-landing'));
const SITE = 'https://www.djandykofficial.com';
if (!fs.existsSync(path.join(LIB, 'src', 'data'))) throw new Error('song library not found at ' + LIB);

const songs = [];
const sheets = new Set(fs.readdirSync(path.join(LIB, 'public', 'downloads', 'song-sheets')));
const files = fs.readdirSync(path.join(LIB, 'src', 'data')).filter(f => f.endsWith('.ts')).sort();
process.removeAllListeners('warning');   // (node reparses the library's .ts files as modules and says so for each)
for (const f of files) {
  const mod = await import(pathToFileURL(path.join(LIB, 'src', 'data', f)).href);
  for (const album of Object.values(mod).filter(v => v && Array.isArray(v.tracks))) {
    for (const t of album.tracks) {
      const sheet = `${album.slug}-${t.slug}.pdf`;
      songs.push({
        id: `${album.slug}/${t.slug}`, album: album.title, title: t.title, n: t.n,
        key: t.key || null, bpm: t.bpm || null, chords: t.chords || null, seconds: t.durationSeconds || null,
        piano: /piano/i.test(t.title) || /piano/i.test(t.slug),
        audio: t.audioSrc ? SITE + t.audioSrc : null,
        sheet: sheets.has(sheet) ? `${SITE}/downloads/song-sheets/${sheet}` : null,
        score: null,
      });
    }
  }
}
// Opus No. 1 Vienna has its own page (no data file): its four movements, their recordings and their real scores
const opusHtml = fs.readFileSync(path.join(LIB, 'src', 'app', 'opus-no-1-vienna', 'content.body.html'), 'utf8');
for (const [slug, title] of [['i-prologue', 'I. Prologue'], ['ii-the-awakening', 'II. The Awakening'], ['iii-the-final-movement', 'III. The Final Movement'], ['iv-coda', 'IV. Coda']]) {
  const audio = `opus-no-1-vienna-${slug}.mp3`, score = `opus-no-1-vienna-${slug}-score.pdf`;
  if (!opusHtml.includes(audio)) continue;
  songs.push({ id: `opus-no-1-vienna/${slug}`, album: 'Opus No. 1: Vienna', title, n: songs.filter(s => s.album === 'Opus No. 1: Vienna').length + 1,
    key: null, bpm: null, chords: null, seconds: null, piano: true, audio: `${SITE}/audio/${audio}`, sheet: null,
    score: opusHtml.includes(score) ? `${SITE}/scores/${score}` : null });
}

if (check) {
  const head = async url => { try { const r = await fetch(url, { method: 'HEAD' }); return r.ok; } catch { return false; } };
  for (const s of songs) {
    s.audioOk = s.audio ? await head(s.audio) : false;
    if (s.sheet) s.sheetOk = await head(s.sheet);
    if (s.score) s.scoreOk = await head(s.score);
  }
}

const out = path.join(ROOT, 'virtual-studio', 'vienna', 'repertoire.js');
fs.writeFileSync(out, `// GENERATED by repertoire-sync.mjs from DJ Andy'K's song library (${path.basename(LIB)}, ${new Date().toISOString().slice(0, 10)}${check ? ', availability checked' : ''}).\n` +
  `// Do not edit: change the library and run the script again.\nexport const REPERTOIRE = ${JSON.stringify(songs, null, 1)};\n`);
const piano = songs.filter(s => s.piano);
console.log(`${songs.length} songs (${piano.length} piano) from ${files.length} album files + Opus No. 1 Vienna`);
console.log(`with key ${songs.filter(s => s.key).length}, chords ${songs.filter(s => s.chords).length}, song sheet ${songs.filter(s => s.sheet).length}, score ${songs.filter(s => s.score).length}, no recording listed ${songs.filter(s => !s.audio).length}`);
if (check) console.log(`recordings reachable ${songs.filter(s => s.audioOk).length}/${songs.filter(s => s.audio).length}; missing: ${songs.filter(s => s.audio && !s.audioOk).map(s => s.id).join(', ') || 'none'}`);
for (const s of piano) console.log(`  ♪ ${s.album} — ${s.title} · ${s.key || 'key —'} · ${s.bpm || '—'} BPM · ${s.chords || 'chords —'} · ${s.sheet ? 'sheet' : s.score ? 'score' : 'no sheet'}${check ? (s.audioOk ? ' · audio ok' : ' · AUDIO MISSING') : ''}`);
console.log('wrote ' + path.relative(ROOT, out));
