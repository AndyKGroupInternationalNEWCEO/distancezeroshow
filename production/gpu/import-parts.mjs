// Takes the transcribed piano parts (transcribe.py on the GPU pod → production/gpu/parts/*.json) into the site:
// assets/piano-parts/<name>.json, and writes virtual-studio/vienna/piano-parts.js, the list of parts and their
// approval. Approvals already given there are kept; a new part starts unapproved (the keys then move only with
// ?keys=preview in the address, for DJ Andy'K to watch and sign it off).
//   node production/gpu/import-parts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = path.join(ROOT, 'production', 'gpu', 'parts'), OUT = path.join(ROOT, 'assets', 'piano-parts');
const REG = path.join(ROOT, 'virtual-studio', 'vienna', 'piano-parts.js');
fs.mkdirSync(OUT, { recursive: true });
let old = {};
try { old = (await import(REG + '?' + Date.now())).PARTS; } catch {}
const parts = {};
for (const f of fs.readdirSync(SRC).filter(f => f.endsWith('.json')).sort()) {
  const p = JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8'));
  fs.writeFileSync(path.join(OUT, f), JSON.stringify({ ...p, approved: undefined }));
  parts[p.song] = { file: 'assets/piano-parts/' + f, notes: p.notes.length, source: p.source, approved: old[p.song]?.approved || null };
}
fs.writeFileSync(REG, `// GENERATED by production/gpu/import-parts.mjs: the grand's piano parts, transcribed from the recordings.
// A part moves the keys once approved: set \`approved: { by: "DJ Andy'K", on: 'YYYY-MM-DD' }\` here after watching it
// (with ?keys=preview the keys also play unapproved parts, to check them). Running the script again keeps approvals.
export const PARTS = ${JSON.stringify(parts, null, 1)};
`);
console.log(Object.entries(parts).map(([k, p]) => `${k}: ${p.notes} notes${p.approved ? ' (approved)' : ''}`).join('\n'));
